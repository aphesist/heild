  await espera(400)
  await portal().getByRole('radio', { name: 'Volume' }).click()
  await portal().getByRole('button', { name: /Contestar um item/ }).click()
  await espera(300)
  await dlg().getByLabel('Item do extrato').selectOption('admissões')
  await dlg().getByLabel('Quantos contestar').fill('1')
  await dlg().getByLabel('Motivo').fill('Admissão contada duas vezes')
  await dlg().getByRole('button', { name: 'Registrar contestação', exact: true }).click()
  await espera(400)
  ok(await visivel(portal().getByText(/1 admissão: Admissão contada duas vezes · em análise/)), 'convidado contesta o extrato com quantidade e motivo')
  await shot('portal-volume')
  await portal().getByRole('button', { name: 'Sair do portal' }).click()
  await espera(400)
  ok(await visivel(p.getByText('Mandamos a CTPS da Maria hoje à tarde')), 'a equipe vê a conversa do contratante (BPO-022)')
  await p.getByLabel('Mensagem', { exact: true }).fill('Obrigada, Igor! Conferimos amanhã.')
  await p.getByRole('button', { name: 'Enviar mensagem' }).click()
  await espera(300)
  await aba('Fila')
  ok(await visivel(p.locator('li', { hasText: 'Férias de Ana em janeiro' }).getByText(/SLA corre/)), 'pedido do portal com anexos entra completo (SLA corre)')
  await aba('Entregas')
  await p.getByRole('button', { name: /Pedir o rascunho/ }).click()
  ok(await visivel(p.getByRole('button', { name: 'Revisar o relatório de Contábil Beta' }), 30000), 'o Atendimento rascunha o relatório do contratante')
  await p.getByRole('button', { name: 'Revisar o relatório de Contábil Beta' }).click()
  await espera(400)
  ok(await visivel(dlg().getByLabel(/Folha do relatório/)), 'relatório do contratante com a marca dele, entregas e desvios explicados')
