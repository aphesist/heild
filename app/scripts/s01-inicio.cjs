// Teste de ponta a ponta da S01 (Início e moldura): busca global (C7), seletor de cliente,
// sino, gaveta do Chat com o Geral, roteador do Assistente (regra, rascunho, ajuda, escolha),
// Time (jobs, memória, configurar), novo integrante (nome validado), Visão geral (calendário,
// pendências), Minha conta (sessões), modo de espera com a tarefa aberta e o celular (menu
// inferior com cinco destinos e configurações só leitura).
// Uso: app servido em http://localhost:6100/ (npx vite --port 6100) e
//      node scripts/s01-inicio.cjs <pasta-das-capturas>
const { chromium } = require('playwright')

;(async () => {
  const out = process.argv[2] || '.'
  const base = process.env.URL_APP || 'http://localhost:6100/'
  const b = await chromium.launch()
  const ctx = await b.newContext({ viewport: { width: 1440, height: 900 } })
  const p = await ctx.newPage()
  const erros = []
  p.on('pageerror', (e) => erros.push(e.message))
  p.on('console', (m) => m.type() === 'error' && erros.push(m.text()))
  let falhas = 0
  const ok = (r, m) => {
    if (!r) falhas++
    console.log((r ? 'ok   ' : 'FALHA') + ' ' + m)
  }
  const shot = (n) => p.screenshot({ path: `${out}/s01-${n}.png` })
  const espera = (ms = 400) => p.waitForTimeout(ms)
  const hash = () => p.evaluate(() => location.hash)
  const texto = () => p.evaluate(() => document.body.innerText)
  const ir = async (h) => {
    await p.goto(base + h)
    await espera(1200)
  }
  /** Espera o texto aparecer (a resposta é escrita palavra por palavra antes dos cartões). */
  const aparece = (t, ms = 12000) => p.waitForFunction((x) => document.body.innerText.includes(x), t, { timeout: ms }).then(() => true, () => false)
  const enviar = async (t, ms = 3200) => {
    await p.getByRole('textbox').last().fill(t)
    await p.keyboard.press('Enter')
    await espera(ms)
  }

  // Entrar
  await p.goto(base)
  await p.waitForFunction(() => document.body && !document.body.innerText.includes('Abrindo o escritório'), null, { timeout: 45000 })
  await espera(700)
  await p.getByRole('button', { name: /Fernanda Lima/ }).first().click()
  await p.getByRole('button', { name: 'Entrar', exact: true }).click()
  await espera(500)
  if (await p.getByLabel('Código').count()) {
    await p.getByLabel('Código').fill('123456')
    await p.keyboard.press('Enter')
  }
  await espera(1200)

  // 1. Busca global (S01-T09)
  await p.keyboard.press('Control+k')
  await espera(300)
  ok(await p.getByRole('combobox', { name: 'Buscar no sistema' }).isVisible(), 'Ctrl+K abre a busca global')
  await p.keyboard.type('12345678000190')
  await espera(500)
  ok((await texto()).includes('Metalúrgica Andrade'), 'CNPJ sem pontuação acha o cliente')
  await p.getByRole('combobox').fill('legal')
  await espera(500)
  ok((await texto()).includes('Painel › Clientes e Societário'), '"legal" acha Societário (sinônimo)')
  await p.getByRole('combobox').fill('padeiro')
  await espera(500)
  ok((await texto()).includes('Áudio:'), 'a busca acha a transcrição do áudio do CRM')
  await p.getByRole('combobox').fill('xyzw nada')
  await espera(500)
  ok((await texto()).includes('Nada encontrado no que você pode ver'), 'sem resultado: mensagem do escopo')
  await p.getByRole('combobox').fill('PGDAS')
  await espera(500)
  await shot('busca')
  await p.keyboard.press('Enter')
  await espera(900)
  ok((await hash()).includes('tarefa='), `Enter leva ao item exato (${await hash()})`)
  await p.keyboard.press('Escape')
  await espera(400)

  // 2. Seletor de cliente (S01-T10)
  await ir('#/painel/fiscal?cliente=c1')
  await p.keyboard.press('Control+j')
  await espera(400)
  ok((await texto()).includes('Grupos econômicos'), 'Ctrl+J abre o seletor com grupos')
  await p.getByRole('button', { name: 'Favoritar Padaria Pão Quente ME' }).first().click()
  await espera(300)
  ok((await texto()).includes('Favoritos'), 'favoritar cria a seção Favoritos')
  await p.getByRole('option', { name: /^Grupo Andrade/ }).click()
  await espera(600)
  ok((await p.getByRole('button', { name: /Cliente: Grupo Andrade/ }).count()) > 0, 'escolher o grupo mostra o grupo no seletor')
  await shot('seletor-grupo')

  // 3. Sino (S01-T07)
  await p.getByRole('button', { name: /^Notificações/ }).click()
  await espera(400)
  const antes = await p.getByRole('button', { name: /^Descartar:/ }).count()
  await p.getByRole('button', { name: /^Descartar:/ }).first().click()
  await espera(400)
  ok((await p.getByRole('button', { name: /^Descartar:/ }).count()) === antes - 1, 'descartar tira o aviso da lista')
  ok((await p.getByRole('radiogroup', { name: 'Categoria' }).count()) > 0, 'sino tem filtro por categoria')
  await shot('sino')
  await p.keyboard.press('Escape')

  // 4. Assistente: roteador (S01-T02)
  await ir('#/inicio/assistente?cliente=c1')
  await enviar('Me avise quando uma certidão estiver para vencer')
  ok(await aparece('Regra para Fiscal vigiar'), 'condição em português vira regra com sim/editar/não')
  await p.getByRole('button', { name: /Sim, vigie/ }).click()
  await espera(500)
  await enviar('Escreva uma mensagem pedindo o extrato')
  // Fase 6: o prazo que o integrante não sabe vem em branco (lacuna); preenchido, vira a prévia.
  ok(await aparece('Só não sei o prazo'), 'pedido de mensagem vem com a lacuna do prazo, sem inventar')
  await p.getByRole('button', { name: 'Lacuna: qual prazo, preencher' }).last().click()
  await espera(300)
  await p.getByRole('button', { name: /^Amanhã/ }).last().click()
  await espera(300)
  await p.getByRole('button', { name: 'Ver a mensagem' }).last().click()
  await espera(400)
  ok(await aparece('Rascunho para'), 'preenchida a lacuna, vira pré-visualização editável')
  await p.locator('button:has-text("Enviar")').last().click()
  await espera(300)
  ok((await texto()).includes('Isto sai ao cliente'), 'enviar pede aprovação')
  await p.getByRole('button', { name: 'Aprovar', exact: true }).last().click()
  await espera(800)
  ok((await texto()).includes('pelo WhatsApp'), 'aprovar envia e avisa')
  await enviar('Como convido alguém para a equipe?')
  ok(await aparece('não gasta o seu limite'), 'pergunta do sistema vai à ajuda')
  await enviar('nota')
  ok(await aparece('Você quer falar de notas'), 'termo ambíguo pergunta com botões')
  await enviar('Monte a pauta da reunião semanal')
  ok(await aparece('Maior risco'), 'pauta da semana vem em tabela')
  await shot('assistente')

  // 5. Gaveta do Chat: o Geral tem a mesma conversa (S01-T06)
  await p.getByRole('button', { name: /^Chat/ }).first().click()
  await espera(500)
  await p.getByRole('tab', { name: /Integrantes/ }).click().catch(() => {})
  await p.getByRole('radio', { name: /Integrantes/ }).click().catch(() => {})
  await espera(600)
  ok((await texto()).includes('Monte a pauta da reunião semanal'), 'a gaveta abre no Geral com a conversa do Assistente')
  await shot('gaveta')
  await p.keyboard.press('Escape')

  // 6. Time: jobs (o job criado pela regra), memória, configurar (S01-T03)
  await ir('#/inicio/time?integrante=i-fiscal')
  await p.getByRole('button', { name: 'Mais opções do integrante' }).click()
  await p.getByRole('button', { name: /^Jobs e gatilhos/ }).click()
  await espera(600)
  ok((await texto()).includes('certidão'), 'o job da regra aparece em Jobs e gatilhos')
  await shot('jobs')
  await p.keyboard.press('Escape')
  await espera(300)
  await p.getByRole('button', { name: 'Mais opções do integrante' }).click()
  await p.getByRole('button', { name: /^Ver memória/ }).click()
  await espera(500)
  await p.getByRole('button', { name: /^Remover:/ }).first().click()
  await espera(300)
  await p.getByRole('button', { name: 'Remover', exact: true }).click()
  await espera(400)
  ok((await texto()).includes('memoria.remover → ok'), 'remover memória mostra o retorno da ferramenta')
  await p.keyboard.press('Escape')
  await espera(300)

  // 7. Novo integrante: nome que imita integrante padrão é recusado (S01-T04)
  await p.getByRole('button', { name: /Novo integrante/ }).first().click()
  await espera(400)
  await p.getByRole('button', { name: /Sentinela do sublimite/ }).click()
  await p.getByRole('button', { name: /Propor/ }).click()
  await espera(2000)
  ok((await p.getByLabel('Nome').inputValue()) === 'Sentinela do sublimite', 'modelo publicado gera a proposta certa')
  await p.getByLabel('Nome').fill('Fiscal')
  await espera(200)
  ok((await texto()).includes('nome de um integrante padrão'), 'nome de integrante padrão é recusado')
  await p.keyboard.press('Escape')

  // 8. Visão geral (S01-T05)
  await ir('#/inicio/visao')
  ok(!(await texto()).includes('Primeiros passos'), 'implantação concluída (S09): sem a faixa Primeiros passos')
  await p.getByRole('radio', { name: 'Todos' }).first().click()
  await espera(400)
  ok((await texto()).includes('Pendências por cliente'), 'pendências por cliente na Visão geral')
  const recebida = p.getByRole('button', { name: /^Marcar recebida:/ }).first()
  if (await recebida.count()) {
    await recebida.click()
    await espera(500)
    ok((await texto()).includes('voltou a andar'), 'marcar recebida baixa e avisa com desfazer')
  }
  await shot('visao')

  // 9. Minha conta: encerrar sessão (S01-T08)
  await p.getByRole('button', { name: 'Conta', exact: true }).click()
  await p.getByRole('button', { name: /Minha conta/ }).click()
  await espera(500)
  const sessoes = await p.getByRole('button', { name: 'Encerrar', exact: true }).count()
  await p.getByRole('button', { name: 'Encerrar', exact: true }).first().click()
  await espera(300)
  ok((await p.getByRole('button', { name: 'Encerrar', exact: true }).count()) === sessoes - 1, 'encerrar uma sessão tira da lista')
  await p.keyboard.press('Escape')
  await espera(300)

  // 10. Modo de espera com a tarefa aberta (S01-T11)
  await ir('#/painel/societario?cliente=c1&tarefa=t18')
  await p.evaluate(() => window.dispatchEvent(new Event('ui-lab:simular-espera')))
  await espera(500)
  ok((await texto()).includes('Em espera'), 'simular parado cobre a área com "Em espera"')
  await p.getByRole('dialog', { name: 'Modo de espera' }).getByRole('button', { name: 'Continuar', exact: true }).click()
  await espera(300)
  ok((await texto()).includes('Você estava em'), 'ao continuar, pergunta da tarefa aberta')
  await shot('espera')
  await p.getByRole('button', { name: /^Continuar em/ }).click()
  await espera(600)
  ok((await hash()).includes('tarefa=t18'), 'continuar reabre a ficha da tarefa')
  await p.keyboard.press('Escape')
  await espera(400)

  // 11. Celular (S01-T01)
  await p.setViewportSize({ width: 390, height: 844 })
  await ir('#/painel/fiscal?cliente=c1')
  const menu = p.getByRole('navigation', { name: 'Menu principal' })
  ok((await menu.getByRole('button').count()) === 5, 'celular: menu inferior com cinco destinos')
  await menu.getByRole('button', { name: /^Tarefas/ }).click()
  await espera(500)
  ok((await texto()).includes('As tarefas dos seus setores'), 'Tarefas abre a TarefasTela da S04')
  await shot('celular-tarefas')
  await p.keyboard.press('Escape')
  await espera(300)
  await menu.getByRole('button', { name: /^Pendências/ }).click()
  await espera(500)
  ok((await texto()).includes('O que os clientes devem'), 'Pendências abre a lista com cobrar')
  await p.keyboard.press('Escape')
  await espera(300)
  await menu.getByRole('button', { name: /^Mais/ }).click()
  await espera(500)
  ok(await p.getByRole('navigation', { name: 'Módulos' }).isVisible(), 'Mais abre a barra com os módulos')
  await p.getByRole('navigation', { name: 'Módulos' }).getByRole('button', { name: 'Configurações' }).click()
  await espera(800)
  ok((await texto()).includes('Edite no computador'), 'Configurações no celular: só leitura com o aviso')
  await shot('celular-config')
  await menu.getByRole('button', { name: /^Início/ }).click()
  await espera(800)
  ok((await hash()).startsWith('#/inicio/visao'), 'Início leva à Visão geral')
  await shot('celular-visao')

  ok(erros.length === 0, `sem erros no console${erros.length ? ': ' + erros.slice(0, 3).join(' | ') : ''}`)
  console.log(falhas ? `\n${falhas} falha(s)` : '\ntudo certo')
  await b.close()
  process.exit(falhas ? 1 : 0)
})()
