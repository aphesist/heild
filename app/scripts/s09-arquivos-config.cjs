// Teste da S09 (Arquivos, Configurações, entrada e implantação): conectores e cofre (contrato C9),
// permissões, Raio-X do Drive em lote, implantação com importação aprovada por cartão, convite
// pelo Usuários e primeiro acesso, Arquivos (confirmar origem, mover com conferência, versões,
// envio com conferência do CNPJ), complemento de marca branca, painel Demonstração, Membro sem
// Configurações, celular e escuro.
// Uso: app servido em http://localhost:6100/ (npx vite --port 6100) e
//      node scripts/s09-arquivos-config.cjs <pasta-das-capturas>
const { chromium } = require('playwright')

;(async () => {
  const out = process.argv[2] || '.'
  const base = process.env.URL_APP || 'http://localhost:6100/'
  const b = await chromium.launch()
  const ctx = await b.newContext({ viewport: { width: 1440, height: 900 } })
  const p = await ctx.newPage()
  const erros = []
  p.on('pageerror', (e) => erros.push(e.message))
  p.on('console', (m) => m.type() === 'error' && !/favicon|Failed to load resource/.test(m.text()) && erros.push(m.text()))
  let falhas = 0
  const ok = (r, m) => {
    if (!r) falhas++
    console.log((r ? 'ok   ' : 'FALHA') + ' ' + m)
  }
  const shot = (n) => p.screenshot({ path: `${out}/s09-${n}.png` })
  const espera = (ms = 400) => p.waitForTimeout(ms)
  const dlg = () => p.getByRole('dialog').last()
  const texto = (t) => p.getByText(t).first()
  const visivel = async (t, ms = 4000) => {
    try {
      await texto(t).waitFor({ state: 'visible', timeout: ms })
      return true
    } catch {
      return false
    }
  }
  const entrar = async (nome) => {
    await p.getByRole('button', { name: new RegExp(nome) }).first().click()
    await p.getByRole('button', { name: 'Entrar', exact: true }).click()
    await espera(400)
    if (await p.getByLabel('Código').count()) {
      await p.getByLabel('Código').fill('123456')
      await p.keyboard.press('Enter')
    }
    await espera(900)
  }
  const ir = async (h) => {
    await p.goto(base + h)
    await espera(1100)
  }
  const confirmarDialogo = async (acao, motivo) => {
    const d = p.getByRole('dialog').last()
    if (motivo) await d.getByRole('textbox').fill(motivo)
    await d.getByRole('button', { name: acao, exact: true }).click()
    await espera(500)
  }

  // 1. Entrar
  await p.goto(base)
  await espera(1200)
  await entrar('Fernanda Lima')
  ok((await p.evaluate(() => location.hash)).startsWith('#/inicio'), 'entra como Administradora')

  // 2. Conectores e cofre (S09-T09, contrato C9)
  await ir('#/config/conectores')
  ok(await visivel('Conectores e cofre'), 'aba Conectores abre')
  ok(await visivel('conexões funcionando'), 'resumo com conexões, pendências, custo e rotinas')
  await shot('conectores')
  const integra = p.locator('[data-conector="integra_contador"]')
  await integra.getByRole('button', { name: 'Testar' }).click()
  ok(await visivel(/Conexão funcionando/, 8000), 'testar conexão mostra as etapas e o resultado (S09-A65)')
  const pref = p.locator('[data-conector="prefeitura_sp"]')
  ok((await pref.textContent()).includes('Erro de credencial'), 'Prefeitura de SP começa com erro de credencial')
  await pref.getByRole('button', { name: 'Reconectar' }).click()
  await dlg().getByLabel('Usuário do portal').fill('escritorio.andrade')
  await dlg().getByLabel('Senha').fill('senha-nova-123')
  await dlg().getByRole('button', { name: 'Conectar' }).click()
  await espera(3500)
  ok((await pref.textContent()).includes('Ativo'), 'reconectar por robô grava no cofre e volta a Ativo (S09-A64)')
  await p.getByRole('button', { name: 'Cofre', exact: true }).click()
  await espera(300)
  await p.getByRole('button', { name: /Vincular e-CNPJ do escritório/ }).click()
  await dlg().getByLabel(/Arquivo do certificado/).fill('escritorio-2027.pfx')
  await dlg().getByLabel('Senha do certificado').fill('1234')
  await dlg().getByRole('button', { name: 'Guardar no cofre' }).click()
  ok(await visivel(/guardado no cofre/, 6000), 'vincular o e-CNPJ do escritório vai ao cofre (S09-A66)')
  const s3 = p.locator('[data-credencial="cr8"]')
  await s3.getByRole('button', { name: 'Mais ações' }).click()
  await p.getByRole('menuitem', { name: 'Revogar' }).click()
  await confirmarDialogo('Revogar', 'chave vazou num print')
  ok(await visivel(/Revogada\. .* pausado/, 5000), 'revogar credencial com motivo pausa e avisa (S09-A67)')
  await p.getByRole('button', { name: 'Mostrar revogadas' }).click()
  ok((await s3.textContent()).includes('revogada'), 'a revogada fica no histórico do cofre')
  await p.getByRole('button', { name: 'Conexões', exact: true }).click()
  await espera(300)
  ok((await p.locator('[data-conector="s3"]').textContent()).includes('Erro de credencial'), 'revogar pausa o conector que usava a credencial')
  await p.getByRole('button', { name: /^Saúde das rotinas/ }).click()
  await espera(300)
  await p.locator('[data-rotina="r3"]').getByRole('button', { name: 'Reprocessar' }).click()
  await espera(3000)
  ok((await p.locator('[data-rotina="r3"]').textContent()).includes('em dia'), 'reprocessar rotina parada (S09-A70, D-38)')
  await p.getByRole('button', { name: 'Custo e teto', exact: true }).click()
  await p.getByRole('button', { name: 'Definir teto' }).click()
  await dlg().getByLabel('Teto em reais').fill('500')
  await dlg().getByRole('button', { name: 'Salvar teto' }).click()
  await espera(500)
  await p.getByRole('button', { name: 'Conexões', exact: true }).click()
  await espera(300)
  ok((await integra.textContent()).includes('Pausado pelo teto'), 'teto abaixo do gasto pausa os conectores pagos (S09-A69)')
  await p.getByRole('button', { name: 'Custo e teto', exact: true }).click()
  await p.getByRole('button', { name: 'Definir teto' }).click()
  await dlg().getByLabel('Teto em reais').fill('5000')
  await dlg().getByRole('button', { name: 'Salvar teto' }).click()
  await espera(400)
  await p.getByRole('button', { name: /^Auditoria mensal/ }).click()
  ok(await visivel('Compartilhada sem termo'), 'auditoria mensal aponta credencial compartilhada sem termo')
  await shot('cofre-auditoria')

  // 3. Painel Demonstração: simular conector com problema (C9 lido em outra tela)
  await p.getByRole('button', { name: /Demonstração/ }).click()
  await espera(300)
  const lab = p.locator('[data-lab="s09"]')
  await lab.getByRole('combobox').nth(1).selectOption('fora_do_ar')
  await lab.getByRole('button', { name: 'Aplicar' }).click()
  await espera(400)
  await p.keyboard.press('Escape')
  await p.getByRole('button', { name: 'Conexões', exact: true }).click()
  await espera(300)
  ok((await integra.textContent()).includes('Fora do ar'), 'painel Demonstração põe o conector fora do ar')

  // 4. Permissões (S09-T05)
  await ir('#/config/permissoes')
  ok(await visivel('Matriz usuário × aba × nível'), 'aba Permissões com a matriz calculada')
  await p.getByRole('button', { name: /João Pereira · Painel › Contábil/ }).click()
  ok(await visivel(/vínculo de gestão/), 'célula explica a regra que decidiu (S09-A32)')
  await p.keyboard.press('Escape')
  await shot('permissoes')

  // 5. Raio-X do Drive (S09-T14)
  await ir('#/config/armazenamento')
  ok(await visivel('Manutenção das pastas'), 'Armazenamento com a manutenção das pastas (D-06)')
  await p.locator('[data-manutencao="m4"]').getByRole('button', { name: 'Arquivo morto' }).click()
  ok(await visivel(/movida para Arquivo morto/), 'ex-cliente vai para o Arquivo morto')
  await p.getByRole('button', { name: /Rodar o Raio-X/ }).first().click()
  await espera(500)
  await p.getByRole('button', { name: 'Rodar diagnóstico' }).click()
  ok(await visivel('Achados para decidir', 15000), 'o Geral lê a lista e entrega o relatório (S09-A96)')
  await shot('raiox')
  await p.locator('[data-achado="rx4"]').getByRole('button', { name: 'Aceitar' }).click()
  await p.getByRole('checkbox', { name: 'Marcar todos os pendentes' }).click()
  await p.getByRole('toolbar', { name: 'Ações em lote' }).getByRole('button', { name: 'Aceitar sugestões' }).click()
  await espera(300)
  await p.getByRole('button', { name: 'Aplicar decisões' }).click()
  ok(await visivel(/decisões aplicadas/), 'decidir achados em lote e aplicar (S09-A97)')
  await p.getByRole('button', { name: 'Dicionário', exact: true }).click()
  await p.getByRole('button', { name: 'Sinônimo' }).first().click()
  await dlg().getByLabel('Nome como aparece nas pastas').fill('Contab')
  await dlg().getByRole('button', { name: 'Adicionar' }).click()
  ok(await visivel('Contab'), 'dicionário de departamentos editável (S09-A98)')
  await p.keyboard.press('Escape')
  await espera(400)

  // 6. Escritório: calendário e D-25; implantação
  await ir('#/config/escritorio')
  await p.getByRole('button', { name: 'Feriado' }).click()
  await dlg().getByLabel('Data').fill('02/02/2027')
  await dlg().getByLabel('Nome').fill('Padroeira da cidade')
  await dlg().getByRole('button', { name: 'Adicionar' }).click()
  ok(await visivel('Padroeira da cidade'), 'feriado entra no calendário do escritório')
  await p.getByRole('switch', { name: 'Trabalhista e DP' }).click()
  ok(await visivel(/obrigações escondidas/), 'serviço não atendido esconde as obrigações (D-25)')
  await p.getByRole('button', { name: 'Rever os passos' }).click()
  await espera(500)
  ok(await visivel('Implantação do escritório'), 'assistente de implantação abre em tela cheia')
  await p.getByRole('button', { name: /4\. Importar clientes/ }).click()
  await p.getByRole('button', { name: 'Ler e conferir' }).click()
  ok(await visivel('Prévia de', 6000), 'importação mostra a prévia com divergências (S09-A93)')
  await shot('implantacao')
  await p.getByRole('button', { name: 'Enviar para aprovação' }).click()
  await espera(400)
  await p.getByRole('dialog').getByRole('button', { name: 'Fechar' }).first().click()
  await espera(400)
  await ir('#/inicio/time?integrante=i-geral')
  await shot('cartao-importacao')
  await p.getByRole('button', { name: /^Aprovar os/ }).last().click({ timeout: 8000 })
  ok(await visivel(/cliente\(s\) importado\(s\)/, 5000), 'aprovar o cartão grava os clientes importados')

  // 7. Usuários: convite com modelo e cancelamento com desfazer
  await ir('#/config/usuarios')
  await p.getByRole('button', { name: 'Convidar' }).first().click()
  await dlg().getByRole('button', { name: 'Recepção' }).click()
  await dlg().getByLabel('Nome').fill('Paula Recepção')
  await dlg().getByLabel('E-mail').fill('paula@contabilandrade.com.br')
  await dlg().getByRole('button', { name: 'Enviar convite' }).click()
  await espera(500)
  ok(await p.locator('[data-convite="paula@contabilandrade.com.br"]').count(), 'convite com o modelo Recepção fica pendente (S09-A24, A31)')
  await p.locator('[data-convite="paula@contabilandrade.com.br"]').getByRole('button', { name: 'Cancelar' }).click()
  await confirmarDialogo('Cancelar convite')
  ok(!(await p.locator('[data-convite="paula@contabilandrade.com.br"]').count()), 'cancelar convite (S09-A30)')
  await p.getByRole('button', { name: 'Desfazer' }).first().click()
  await espera(400)
  ok(await p.locator('[data-convite="paula@contabilandrade.com.br"]').count(), 'desfazer volta o convite')

  // 8. Arquivos (S09-T01, T02)
  await ir('#/arquivos/pastas')
  ok(await visivel('Precisa de atenção'), 'Arquivos mostra o que precisa de atenção')
  await p.locator('[data-fila="origem"]').first().getByRole('button', { name: 'Confirmar origem' }).click()
  await dlg().getByRole('button', { name: 'Confirmar origem' }).click()
  ok(await visivel(/Origem confirmada/), 'confirmar origem atribui quem mandou e abre a tarefa (S09-A08)')
  await shot('arquivos')
  await p.getByRole('textbox', { name: 'Buscar arquivo' }).fill('Contrato social consolidado')
  await espera(400)
  await p.locator('[data-doc="Contrato social consolidado.pdf"]').first().getByRole('button', { name: /^Ações de/ }).click()
  await p.getByRole('menuitem', { name: 'Versões lado a lado' }).click()
  ok(await visivel(/entrada da sócia Juliana Prado/), 'versões lado a lado (S09-A05)')
  await shot('versoes')
  await p.keyboard.press('Escape')
  await espera(300)
  await p.getByRole('textbox', { name: 'Buscar arquivo' }).fill('Holerites 10-2026')
  await espera(400)
  await p.locator('[data-doc="Holerites 10-2026.pdf"]').first().getByRole('button').first().click()
  await espera(500)
  ok(await visivel('Registro de entrega'), 'visualizador abre com a marca do escritório (S09-A14)')
  await p.getByRole('button', { name: 'Enviar ao cliente' }).click()
  ok(await visivel(/CNPJ do documento .* é o de/), 'enviar ao cliente confere o CNPJ antes (S09-A16, D-34)')
  await dlg().getByRole('button', { name: 'Preparar o cartão' }).click()
  ok(await visivel(/Cartão de envio/), 'envio vira cartão de aprovação')
  await p.keyboard.press('Escape')
  await espera(300)
  await p.getByRole('textbox', { name: 'Buscar arquivo' }).fill('Folha analítica 10-2026')
  await espera(400)
  await p.locator('[data-doc="Folha analítica 10-2026.pdf"]').first().getByRole('button', { name: /^Ações de/ }).click()
  await p.getByRole('menuitem', { name: 'Mover ou renomear' }).click()
  await dlg().getByLabel('Cliente').selectOption({ index: 3 })
  await dlg().getByRole('button', { name: 'Enviar para conferência' }).click()
  ok(await visivel(/enviada para conferência/), 'mudar de cliente vai para conferência (S09-A04)')
  await p.getByRole('textbox', { name: 'Buscar arquivo' }).fill('')
  await espera(400)
  await p.getByRole('button', { name: /Em conferência/ }).click()
  await p.locator('[data-fila="conferencia"]').first().getByRole('button', { name: 'Confirmar' }).click()
  ok(await visivel(/O registro de entrega seguiu/), 'Gestor ou Administrador confirma a mudança')

  // 9. Marca branca como complemento (S09-T07, T10)
  await ir('#/config/assinatura')
  ok(await visivel('incluído no plano'), 'App do cliente incluído no plano')
  await p.locator('[data-complemento="marca_branca"]').getByRole('button', { name: 'Remover' }).click()
  await confirmarDialogo('Remover')
  await ir('#/config/tema')
  ok(await visivel('Sem marca branca'), 'sem o complemento, o Tema mostra a identidade da plataforma (S09-A44)')
  ok(await visivel('Requinte'), 'seletor único com fábrica, exemplos, Condesp e Requinte')
  await shot('tema-sem-marca')
  await ir('#/config/assinatura')
  await p.locator('[data-complemento="marca_branca"]').getByRole('button', { name: 'Adicionar' }).click()
  await confirmarDialogo('Adicionar')

  // 10. Primeiro acesso por convite (S09-T12)
  await p.getByRole('button', { name: /Demonstração/ }).click()
  await p.getByRole('button', { name: /Voltar para a tela de login/ }).click()
  await espera(800)
  await p.getByRole('button', { name: /Carla Mendes/ }).click()
  ok(await visivel('Primeiro acesso'), 'convite abre o primeiro acesso')
  await p.getByRole('button', { name: 'Continuar' }).click()
  await p.getByLabel('Senha', { exact: true }).fill('carla2026x')
  await p.getByLabel('Repita a senha').fill('carla2026x')
  await p.getByRole('button', { name: 'Continuar' }).click()
  await p.getByRole('button', { name: 'Continuar' }).click()
  await p.getByRole('switch', { name: /Li e aceito/ }).click()
  await p.getByRole('button', { name: 'Aceitar e entrar' }).click()
  await espera(1200)
  ok((await p.evaluate(() => location.hash)).startsWith('#/'), 'aceitar o convite entra no sistema (S09-A90)')
  ok(!(await p.getByRole('button', { name: 'Configurações', exact: true }).count()), 'Membro não vê Configurações')

  // 11. Esqueci a senha
  await p.getByRole('button', { name: /Demonstração/ }).click()
  await p.getByRole('button', { name: /Voltar para a tela de login/ }).click()
  await espera(700)
  await p.getByRole('button', { name: 'Esqueci a senha' }).click()
  await p.getByLabel('E-mail').fill('ana@contabilandrade.com.br')
  await p.getByRole('button', { name: 'Enviar código' }).click()
  await p.getByLabel('Código do e-mail').fill('654321')
  await p.getByRole('button', { name: 'Continuar' }).click()
  await p.getByLabel('Senha nova').fill('nova-senha-9')
  await p.getByRole('button', { name: 'Salvar senha' }).click()
  ok(await visivel('Senha trocada'), 'esqueci a senha com código e senha nova (S09-A89)')
  await shot('login')

  // 12. Celular e escuro
  const cel = await b.newContext({ viewport: { width: 390, height: 844 }, colorScheme: 'dark', deviceScaleFactor: 1 })
  const m = await cel.newPage()
  await m.goto(base)
  await m.waitForTimeout(1200)
  await m.getByRole('button', { name: /Fernanda Lima/ }).first().click()
  await m.getByRole('button', { name: 'Entrar', exact: true }).click()
  await m.waitForTimeout(400)
  await m.getByLabel('Código').fill('123456')
  await m.keyboard.press('Enter')
  await m.waitForTimeout(900)
  for (const [h, n] of [['#/config/conectores', 'cel-conectores'], ['#/config/permissoes', 'cel-permissoes'], ['#/arquivos/pastas', 'cel-arquivos']]) {
    await m.goto(base + h)
    await m.waitForTimeout(1200)
    const larg = await m.evaluate(() => document.documentElement.scrollWidth)
    ok(larg <= 392, `${h} sem rolagem horizontal no celular (${larg}px)`)
    await m.screenshot({ path: `${out}/s09-${n}.png` })
  }

  ok(erros.length === 0, `sem erro no console (${erros.slice(0, 3).join(' | ')})`)
  console.log(falhas ? `\n${falhas} falha(s)` : '\nTudo certo')
  await b.close()
  process.exit(falhas ? 1 : 0)
})()
