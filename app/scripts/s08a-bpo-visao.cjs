  ok(await visivel(ficha().getByRole('list', { name: 'Passos da implantação' })), 'a implantação começa direto de Clientes')
  await fecharTudo()
  await p.getByRole('tab', { name: 'Contatos' }).click()
  await espera(600)
  await p.getByRole('radio', { name: 'Aprovam pagamentos' }).click()
  await espera(300)
  ok((await p.getByRole('list', { name: 'Contatos dos clientes' }).getByText(/aprova até/).count()) >= 1, 'contatos filtrados por quem aprova pagamentos')
  // Celular nos Clientes
  await p.setViewportSize({ width: 390, height: 844 })
  await p.goto(`${base}#/clientes/cadastro?cliente=todos`)
  await espera(900)
  ok((await p.evaluate(() => document.documentElement.scrollWidth)) <= 392, 'Clientes no celular sem rolagem lateral')
  await shot('celular-clientes')
  await p.setViewportSize({ width: 1440, height: 900 })
