  await entrar('Marina Teixeira')
  await ir('visao')
  ok(await visivel(p.getByRole('list', { name: 'Carteira por analista' })), 'Gestor do BPO vê por analista')
  ok(!(await p.getByText('margem do BPO').count()), 'Gestor do BPO sem Gestão ou Financeiro não vê margem')

  // 10. Clientes no cenário "Só BPO" (T08)
  await entrar('Fernanda Lima')
  await lab()
  await p.getByRole('radio', { name: 'Só BPO' }).click()
  await espera(600)
  await fecharLab()
  await p.goto(`${base}#/clientes/cadastro?cliente=todos`)
  await espera(1000)
  ok(await visivel(p.getByRole('list', { name: 'Clientes' })), 'Clientes no lugar do Painel (BPO puro)')
  ok(!(await p.getByRole('list', { name: 'Clientes' }).getByText('Contabilidade', { exact: true }).count()), 'sem o pacote Contábil no BPO puro')
  ok(await p.getByRole('list', { name: 'Clientes' }).getByText('Oficina S08a Ltda').count(), 'cliente com o BPO encerrado continua no cadastro')
  await p.getByRole('radio', { name: /^Em implantação/ }).click()
  await espera(300)
  ok((await p.getByRole('list', { name: 'Clientes' }).getByRole('listitem').count()) >= 1, 'filtro por situação do BPO')
  await p.getByRole('radio', { name: /^Todos/ }).first().click()
  await shot('clientes')
  await p.getByRole('button', { name: 'Novo cliente' }).click()
  await espera(400)
  await gaveta().getByLabel('Razão social').fill('Cliente Duplicado')
  await gaveta().getByLabel('CNPJ ou CPF').fill('34.567.890/0001-12')
  ok(await visivel(gaveta().getByText(/Este documento já está no cadastro/)), 'novo cliente confere o documento (sem duplicar)')
  ok(await gaveta().getByRole('button', { name: 'Cadastrar' }).isDisabled(), 'não grava duplicado')
  await gaveta().getByLabel('Razão social').fill('Cafeteria S08a Ltda')
  await gaveta().getByLabel('CNPJ ou CPF').fill('44.555.666/0001-77')
  await gaveta().getByRole('button', { name: 'Cadastrar' }).click()
  await espera(800)
  ok(await visivel(p.getByRole('dialog').getByText('Pôr empresa no BPO')), 'cadastrar já abre "Pôr empresa no BPO" com o cliente escolhido')
  await p.getByRole('dialog').last().getByRole('button', { name: 'Começar a implantação' }).click()
